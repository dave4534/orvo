#!/usr/bin/env node
// npm run prep:data
// Copies the dataset from ../Data Generation into src/data and removes `ground_truth`
// (the answer key for the planted agent mistakes) so it never reaches the client bundle.
// Re-run whenever the dataset is rebuilt.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";

const SOURCE = join(process.cwd(), "..", "Data Generation");
const TARGET = join(process.cwd(), "src", "data");

mkdirSync(TARGET, { recursive: true });

const data = JSON.parse(readFileSync(join(SOURCE, "data.json"), "utf8"));
for (const claim of data.claims) delete claim.ground_truth;
// The dataset's mistake_kind labels belong to the answer key too.
if (data.enums) delete data.enums.mistake_kind;
writeFileSync(join(TARGET, "data.json"), JSON.stringify(data, null, 2) + "\n");

let types = readFileSync(join(SOURCE, "types.ts"), "utf8");
types = types.replace(/\/\*\* For designers and tests only[\s\S]*?\nexport interface GroundTruth \{[\s\S]*?\n\}\n\n/, "");
types = types.replace(/\n\s*ground_truth: GroundTruth;/, "");
types = types.replace(/ \(see ground_truth\)/, "");
if (/ground_truth|GroundTruth/.test(types)) {
  console.error("prep:data failed: ground_truth is still referenced in types.ts");
  process.exit(1);
}
writeFileSync(
  join(TARGET, "types.ts"),
  "// Generated by scripts/prep-data.mjs from ../Data Generation/types.ts. Do not edit.\n" + types,
);

const leaked = readFileSync(join(TARGET, "data.json"), "utf8").includes("ground_truth");
if (leaked) {
  console.error("prep:data failed: ground_truth is still in data.json");
  process.exit(1);
}
console.log(`prep:data ok: ${data.claims.length} claims, ground_truth removed`);
